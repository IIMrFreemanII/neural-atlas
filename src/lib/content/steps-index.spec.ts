import { describe, expect, it } from 'vitest';
import { allLessons } from './curriculum.ts';
import { STEPS } from './steps-index.ts';

// The project has no Node type definitions, so node:fs is loaded through a variable and typed by hand.
const fsName = 'node:fs';
const fs = (await import(/* @vite-ignore */ fsName)) as { writeFileSync(url: URL, data: string): void };
const write = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env.GEN_STEPS_INDEX;

const HELP = 'steps-index.ts is out of date: run `node --experimental-strip-types scripts/gen-steps-index.ts`';

async function actual() {
	const rows: { track: string; lesson: string; step: number; title: string }[] = [];
	for (const meta of allLessons) {
		if (meta.status !== 'ready' || !meta.load) continue;
		const { default: lesson } = await meta.load();
		lesson.steps.forEach((s, step) => rows.push({ track: meta.track, lesson: meta.id, step, title: s.title }));
	}
	return rows;
}

describe('steps index', () => {
	it('matches the step titles of every ready lesson', async () => {
		const rows = await actual();
		if (write) {
			const body = rows
				.map((r) => `\t{ track: '${r.track}', lesson: '${r.lesson}', step: ${r.step}, title: ${JSON.stringify(r.title)} }`)
				.join(',\n');
			const out = `// Generated by scripts/gen-steps-index.ts — do not edit.\nimport type { TrackId } from '../lessons/types.ts';\n\nexport const STEPS: { track: TrackId; lesson: string; step: number; title: string }[] = [\n${body}\n];\n`;
			fs.writeFileSync(new URL('./steps-index.ts', import.meta.url), out);
			expect(rows.length).toBeGreaterThan(0);
			return;
		}
		expect(STEPS, HELP).toEqual(rows);
	}, 60_000);
});
